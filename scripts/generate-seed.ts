      s.containers
        .map((c, i) => `  (${q(s.id)}, ${i}, ${q(c.number)}, ${q(c.type)}, ${q(c.sealNumber)}, ${n(c.weightKg)}, ${q(c.status)}, ${n(c.ddRiskUsd)})`)
