// Generates migrations/0002_seed.sql from the deterministic demo-data generator.
// Run: npm run seed:generate  (output is byte-stable; commit the result)
import { createHash, pbkdf2Sync } from 'node:crypto'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { generateShipments } from '../src/data/generator'
import { CARRIERS, CONSIGNEES, FORWARDERS, SHIPPERS } from '../src/data/constants'
import { iso, TODAY } from '../src/data/random'

const PBKDF2_ITERATIONS = 100000
const DEMO_PASSWORD = 'tidelane-demo'

const q = (v: string | null | undefined): string =>
  v === null || v === undefined ? 'NULL' : `'${v.replace(/'/g, "''")}'`
const n = (v: number | null | undefined): string => (v === null || v === undefined ? 'NULL' : String(v))

function passwordHash(email: string): string {
  // Salt derived from the email so regeneration is byte-identical.
  const salt = createHash('sha256').update(`tidelane-salt:${email}`).digest().subarray(0, 16)
  const hash = pbkdf2Sync(DEMO_PASSWORD, salt, PBKDF2_ITERATIONS, 32, 'sha256')
  return `pbkdf2$${PBKDF2_ITERATIONS}$${salt.toString('base64')}$${hash.toString('base64')}`
}

// --- Organizations -----------------------------------------------------------
interface Org {
  id: number
  name: string
  type: string
}
const orgs: Org[] = [{ id: 1, name: 'Tidelane', type: 'internal' }]
let orgId = 2
for (const s of SHIPPERS) orgs.push({ id: orgId++, name: s.name, type: 'shipper' })
for (const c of CONSIGNEES) orgs.push({ id: orgId++, name: c.name, type: 'consignee' })
for (const f of FORWARDERS) orgs.push({ id: orgId++, name: f.name, type: 'forwarder' })
for (const c of CARRIERS) orgs.push({ id: orgId++, name: c.name, type: 'carrier' })
const orgByName = new Map(orgs.map((o) => [o.name, o.id]))

